export function isRecommendationMetadataTag(tag: string): boolean {
  if (STRUCTURAL_METADATA_TAGS.has(tag) || LANGUAGE_METADATA_TAGS.has(tag)) return true;

  const parts = tag.split(" ").filter(Boolean);
  if (parts.length < 2 || parts.length > 3) return false;

  const [language, region] = parts;
  return LANGUAGE_METADATA_TAGS.has(language)
    && /^[a-z]{2,3}$/.test(region ?? "")
    && (parts.length === 2 || /^[a-z]{2,3}$/.test(parts[2] ?? ""));
}
