import { describe, expect, it } from "vitest";
import fs from "node:fs/promises";
import path from "node:path";
import { store } from "../../store/state.svelte";
import { loadSourceInventory } from "./sourceInventory";
import { analyzeBackupReconciliation, overlayEntryFromAnalysis } from "./analyze";
import { gql } from "../client";
import { GET_TRACKERS } from "../queries";
import type { OverlayFile } from "./types";
import type { Tracker } from "../types";

const BACKUP_PATH = "C:\\Users\\jhow-\\Documents\\Temp\\epigraph-restore-validation\\backup-under-test.tachibk";
describe("overlay reuse validation harness", () => {
  it("reuses a persisted overlay generated by the current build on a fresh disposable server", async () => {
    store.settings.serverUrl = "http://127.0.0.1:4571";
    store.settings.autoStartServer = false;

    try {
      await fetch("http://127.0.0.1:4571/api/graphql", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ query: "{ __typename }" }),
      });
    } catch {
      console.warn("Skipping overlay reuse integration test because the disposable validation server is not running on 127.0.0.1:4571.");
      return;
    }

    const backupBytes = await fs.readFile(BACKUP_PATH);
    const [inventory, trackersData] = await Promise.all([
      loadSourceInventory(),
      gql<{ trackers: { nodes: Tracker[] } }>(GET_TRACKERS),
    ]);

    const emptyOverlay: OverlayFile = { version: 1, entries: {} };
    const { analysis: firstAnalysis } = await analyzeBackupReconciliation(
      new Uint8Array(backupBytes),
      inventory.inventory,
      trackersData.trackers.nodes ?? [],
      emptyOverlay,
    );

    const generatedOverlay: OverlayFile = {
      version: 1,
      entries: {
        [firstAnalysis.backupFingerprint]: overlayEntryFromAnalysis(firstAnalysis),
      },
    };

    const { analysis: reusedAnalysis } = await analyzeBackupReconciliation(
      new Uint8Array(backupBytes),
      inventory.inventory,
      trackersData.trackers.nodes ?? [],
      generatedOverlay,
    );

    const firstWarnings = firstAnalysis.warnings.map((warning) => warning.message);
    const reusedWarnings = reusedAnalysis.warnings.map((warning) => warning.message);

    await fs.writeFile(
      path.join("C:\\Users\\jhow-\\Documents\\Temp\\epigraph-restore-validation", "overlay-reuse-analysis-first.json"),
      JSON.stringify(firstAnalysis, null, 2),
      "utf8",
    );
    await fs.writeFile(
      path.join("C:\\Users\\jhow-\\Documents\\Temp\\epigraph-restore-validation", "overlay-reuse-generated-overlay.json"),
      JSON.stringify(generatedOverlay, null, 2),
      "utf8",
    );
    await fs.writeFile(
      path.join("C:\\Users\\jhow-\\Documents\\Temp\\epigraph-restore-validation", "overlay-reuse-analysis-second.json"),
      JSON.stringify(reusedAnalysis, null, 2),
      "utf8",
    );

    expect(firstAnalysis.exactMatches).toHaveLength(12);
    expect(firstAnalysis.autoReconciled).toHaveLength(0);
    expect(firstAnalysis.needsReview).toHaveLength(0);
    expect(firstAnalysis.unresolved).toHaveLength(23);
    expect(firstWarnings).toHaveLength(0);

    expect(reusedAnalysis.backupFingerprint).toBe(firstAnalysis.backupFingerprint);
    expect(reusedAnalysis.sourceInventoryFingerprint).toBe(firstAnalysis.sourceInventoryFingerprint);
    expect(reusedAnalysis.exactMatches).toHaveLength(12);
    expect(reusedAnalysis.autoReconciled).toHaveLength(0);
    expect(reusedAnalysis.needsReview).toHaveLength(0);
    expect(reusedAnalysis.unresolved).toHaveLength(23);
    expect(reusedWarnings).toHaveLength(0);
    expect(firstAnalysis.unresolved[0]?.sampleManga.length ?? 0).toBeGreaterThan(0);
    expect(reusedAnalysis.unresolved[0]?.sampleManga.length ?? 0).toBe(0);

  }, 120_000);
});
